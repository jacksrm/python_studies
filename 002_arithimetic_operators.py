# Arithmetic Operators
# -> +  Sum
# -> -  Subtraction
# -> *  Multiplication
# -> /  Division
# -> ** Power
# -> // Integer Division
# -> %  Module
n1 = 5
n2 = 2

print(f"             Sum: {n1} + {n2} = {n1 + n2}")
print(f"     Subtraction: {n1} - {n2} = {n1 - n2}")
print(f"  Multiplication: {n1} * {n2} = {n1 * n2}")
print(f"        Division: {n1} / {n2} = {n1 / n2}")
print(f"           Power: {n1} ** {n2} = {n1**n2}")
print(f"Integer Division: {n1} // {n2} = {n1 // n2}")
print(f"          Module: {n1} % {n2} = {n1 % n2}")

# Precedence Order
# 1. ()
# 2. **
# 3. * / // %
# 4. + -
# If theres more than one operator of the same precedence
# from left -> to right
# first -> second
